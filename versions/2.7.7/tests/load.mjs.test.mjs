import assert from 'node:assert/strict';
import {restoreCalculationVersion} from '../src/calculation-version.js';
import {BitrixAdapter} from '../src/bitrix.js';
import {calculateQuote, validateConfig, withCoatingOptions} from '../src/calculator.js';
import {readFile} from 'node:fs/promises';
const config = withCoatingOptions(validateConfig(JSON.parse(await readFile(new URL('../data/coatings.example.json', import.meta.url), 'utf8'))));
const fixture = {schemaVersion:1,version:'v1',deal:{id:'42',companyName:'ООО Тест'},parameters:{currency:'RUB',rounding:'unit',rows:[{productId:'9',productName:'Опора',basePrice:'100,50',quantity:'2',k1:'1,2',k2:'1,1',k3:'1',coatingCode:'none',executionTerm:'20',fastenersEnabled:true,fasteners:'5'}]}};
const restored=restoreCalculationVersion(fixture,'42',config);
assert.equal(restored.rows[0].basePrice,'100,50');
assert.equal(restored.rows[0].fasteners,'5');
assert.equal(restored.rows[0].needsCatalogPrice,false);
assert.ok(calculateQuote(restored.rows,config,{}).valid);
assert.throws(()=>restoreCalculationVersion(fixture,'43',config),/текущей сделки/);
assert.throws(()=>restoreCalculationVersion({...fixture,schemaVersion:9},'42',config));
assert.throws(()=>restoreCalculationVersion({...fixture,parameters:{...fixture.parameters,rows:[]}},'42',config));
const calls=[];
const adapter=new BitrixAdapter({sdk:{callMethod(method,params,cb){calls.push(method);cb({error:()=>null,data:()=>({ID:'1',NAME:'x.json',TYPE:'file',PARENT_ID:'999',DOWNLOAD_URL:'https://portal.example/file'})});}}});adapter.connected=true;
await assert.rejects(adapter.loadCalculationVersion('77','1'),/папке/);
assert.deepEqual(calls,['disk.file.get']);
console.log('PASS: restoration, decimal inputs, valid calculation, wrong deal/schema rejected, wrong Disk folder rejected');
